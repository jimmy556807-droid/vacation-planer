export const DICTS: Record<Lang, Dict> = { "zh-Hant": zhHant, "zh-Hans": zhHans, en };

export const LangContext = createContext<Lang>("zh-Hant");
export function useLang() {
  return useContext(LangContext);
}
export function useT() {
  return DICTS[useLang()];
}

export function weatherIndex(code: number | null) {
  if (code === null) return 0;
  if (code === 0) return 1;
  if (code <= 2) return 2;
  if (code === 3) return 3;
  if (code <= 48) return 4;
  if (code <= 57) return 5;
  if (code <= 67) return 6;
  if (code <= 77) return 7;
  if (code <= 82) return 8;
  if (code <= 86) return 9;
  return 10;
}

export function localeOf(lang: Lang) {
  return lang === "en" ? "en-HK" : lang === "zh-Hans" ? "zh-CN" : "zh-HK";
}
